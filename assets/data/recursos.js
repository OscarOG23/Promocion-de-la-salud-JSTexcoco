/* ================================================
   RECURSOS — ÍNDICE ÚNICO
   ================================================
   Fuente única de TODOS los materiales del sitio.
   Sustituye a biblioteca.js, talleres.js, formularios.js,
   psicologia.js y a las tarjetas que estaban escritas
   a mano dentro de entornos.html.

   CÓMO AÑADIR UN RECURSO: copia un objeto {...} y edita.
   Los tres primeros campos son las facetas por las que
   se filtra y se enlaza desde otras páginas.

   programa:  transversal | promocion | adicciones | salud-mental | entornos
   tipo:      formato | normativa | nom | manual | grafico |
              presentacion | documento | taller | formulario | enlace
   tema:      etiquetas controladas (opcional). Vocabulario actual:
              · determinantes: alimentacion, actividad, salud-sexual,
                entornos-fisicos, entornos-psicosociales, infancia,
                diversidad, derecho-salud, participacion
              · entornos: escuelas, comunidades, laborales, unidades
              · otros: psicologia, ferias
   estado:    ok         → se muestra como enlace
              pendiente  → se muestra apagado, SIN enlace (no más href="#")
              rehospedar → funciona, pero el archivo vive en la cuenta Wix

   subtema:   agrupa dentro de un tema. En los talleres es la categoría
              del catálogo («Prevención de Cáncer», «Síndrome Metabólico»…)
              y con ella se arman los grupos plegables de promocion.html.
   ================================================


   UN RECURSO CON VARIOS ARCHIVOS
   ==============================
   Una ficha ya no está limitada a un archivo (`url`) más su carpeta
   (`complementos`). Cuando un tema trae paquete completo —presentación,
   guion, audio, infografía, fuentes— se usa `materiales`, que no tiene tope:

     { titulo: 'Diabetes',
       programa: 'promocion', tipo: 'taller',
       tema: ['alimentacion'], subtema: 'Síndrome Metabólico',
       publico: 'Población abierta',
       materiales: [
         { tipo: 'Presentación', icono: 'presentacion', url: 'talleres/C02-02.html' },
         { tipo: 'Guion del taller', icono: 'documento', url: GD.doc('1AbC…') },
         { tipo: 'Audio resumen',   icono: 'audio',      url: GD.archivo('1DeF…') },
         { tipo: 'Infografía',      icono: 'imagen',     url: GD.archivo('1GhI…') },
         { tipo: 'Fuentes',         icono: 'carpeta',    url: GD.carpeta('1JkL…') },
         { tipo: 'Cuaderno de trabajo', icono: 'documento' },   // ← sin url = en elaboración
       ] }

   · El PRIMER material es el botón principal; los demás salen en gris.
   · A partir del cuarto se pliegan tras «+N materiales», así una ficha
     con diez archivos no aplasta a las de al lado.
   · Un material SIN `url` se pinta apagado y sin enlace («en elaboración»).
     Es la forma de dejar anunciado lo que todavía se está preparando,
     sin colgar un enlace que no lleva a ninguna parte.
   · `icono` puede ser: presentacion · documento · hoja · video · audio ·
     imagen · carpeta · mapa · formulario · enlace · descarga.
     Si se omite, se decide solo (enlace externo o descarga).

   `url` + `accion` + `complementos` siguen funcionando igual: los 176
   recursos que ya existen no hay que tocarlos, y los dos formatos
   pueden convivir en esta misma lista.
   ================================================ */


